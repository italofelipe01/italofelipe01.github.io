const reverseTranslations = Object.fromEntries(
  Object.entries(ptTranslations).map(([english, portuguese]) => [
    portuguese,
    english,
  ])
);

const patterns = {
  pt: [
    [/^Created on (.+)$/u, "Criado em $1"],
    [/^Updated on (.+)$/u, "Atualizado em $1"],
    [/^(.+) committed on (.+)$/u, "$1 commitado em $2"],
  ],
  en: [
    [/^Criado em (.+)$/u, "Created on $1"],
    [/^Atualizado em (.+)$/u, "Updated on $1"],
    [/^(.+) commitado em (.+)$/u, "$1 committed on $2"],
  ],
};

function preserveOuterWhitespace(original, translated) {
  const leading = original.match(/^\s*/u)?.[0] || "";
  const trailing = original.match(/\s*$/u)?.[0] || "";

  return `${leading}${translated}${trailing}`;
}

export function translateText(value, language) {
  if (!value) {
    return value;
  }

  if (language === "en") {
    const englishText = reverseTranslations[value.trim()];

    if (englishText) {
      return preserveOuterWhitespace(value, englishText);
    }
  }

  const trimmed = value.trim();
  const dictionary = language === "pt" ? ptTranslations : reverseTranslations;
  const direct = dictionary[trimmed];

  if (direct) {
    return preserveOuterWhitespace(value, direct);
  }

  for (const [pattern, replacement] of patterns[language] || []) {
    if (pattern.test(trimmed)) {
      return preserveOuterWhitespace(value, trimmed.replace(pattern, replacement));
    }
  }

  return value;
}
